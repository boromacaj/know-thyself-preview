/** A line that speaks of the reader ("in yourself"), which cannot describe the other side's part. */
const ADDRESSES_READER = /\b(?:you|your|yours|yourself)\b/i;
/** The card's reading for an area in an orientation, or null where it has none and is read in general. A place for the other side never gets a line about the reader. */
export function areaReadingOf(cardId, orientation, area, place) {
    if (!area)
        return null;
    const sides = TAROT_AREA_READINGS_EN[cardId]?.[area];
    const side = sides ? (orientation === 'reversed' ? sides[1] : sides[0]) : null;
    if (!side)
        return null;
    const [meaning, ask] = side;
    if (place === 'other' && ADDRESSES_READER.test(meaning))
        return null;
    return { meaning, ask };
}
