/**
 * THE SEVENTY-EIGHT CARDS IN ENGLISH.
 *
 * Fragments, not paragraphs. Each card gives five short pieces that the composer
 * assembles into sentences about TWO cards - "X, and then Y" - which is the only
 * way 456,456 readings can exist without being written. A paragraph per card can
 * only be printed whole, and three paragraphs printed whole is the failure this
 * whole layer exists to avoid.
 *
 *   dynamic       a noun phrase. Reads after "is" or "of": "the energy is a step
 *                 taken before the ground is proven".
 *   tag           two to four words, for tight positions.
 *   constructive  verb phrase: what this supports when it goes well.
 *   difficult     verb phrase: what the same pattern costs. NOT a reversal - the
 *                 card upright already contains both.
 *   asks          what the pattern asks for, used when the card lands in
 *                 Guidance. A stance, never an instruction about a life.
 *
 * WRITTEN AGAINST THE SEMANTIC MODEL, NOT AGAINST A SOURCE. Waite's wording is
 * Edwardian and distinctive and none of it is reproduced here; his text informed
 * the semantics, and these phrases were written from those. No modern Tarot copy
 * was consulted while writing them.
 *
 * NOTHING HERE PREDICTS. No phrase names an event, a person, a diagnosis, an
 * amount of money or another person's private thoughts. The difficult column in
 * particular is about a pattern's cost, never about something that will happen.
 */
