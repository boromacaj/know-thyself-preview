/**
 * The reference content's own extent: Head's apex (y=10.63) down to Root's
 * bottom edge (y=703.71), horizontally centred on the spine. The canvas fit
 * below is derived from these, so the mapping comes out of the reference
 * itself rather than being hand-tuned.
 */
export const REFERENCE_CONTENT_TOP = 10.63;
export const REFERENCE_CONTENT_BOTTOM = 703.71;
/**
 * Reference -> KNOW THYSELF canvas fit.
 *
 * Our canvas stays 800x1000 and the graph stays centred on (400,500). The
 * scale puts the reference's content height (693.08 units) at ~901 canvas
 * units, which lands the graph's horizontal extent (Spleen's left edge to
 * Solar Plexus's right edge) at 140.6..659.4 - within a unit of the envelope
 * the previous procedural geometry occupied (140.27..659.74). The surrounding
 * Premium Earth layout therefore sees the same footprint it already framed;
 * only the geometry inside it changes.
 */
export const REFERENCE_SCALE = 1.3;
const REFERENCE_PIVOT = {
    x: REFERENCE_CENTERLINE_X + 0.5,
    y: (REFERENCE_CONTENT_TOP + REFERENCE_CONTENT_BOTTOM) / 2,
};
const CANVAS_PIVOT = { x: 400, y: 500 };
function round(value) {
    return Math.round(value * 100) / 100;
}
/** Map a point from reference viewBox space into our 800x1000 canvas. */
export function refToCanvas(x, y) {
    return {
        x: CANVAS_PIVOT.x + (x - REFERENCE_PIVOT.x) * REFERENCE_SCALE,
        y: CANVAS_PIVOT.y + (y - REFERENCE_PIVOT.y) * REFERENCE_SCALE,
    };
}
export function refRectToCanvas(rect) {
    const origin = refToCanvas(rect.x, rect.y);
    return {
        x: origin.x,
        y: origin.y,
        width: rect.width * REFERENCE_SCALE,
        height: rect.height * REFERENCE_SCALE,
    };
}
/**
 * Rewrite one of the flattened reference paths into canvas space. Every path
 * in REFERENCE_CENTER_PATHS uses only absolute M / L / C / Z, so each numeric
 * token is one half of an (x,y) pair and can be mapped pairwise.
 */
export function refPathToCanvas(d) {
    const tokens = d.trim().split(/[\s,]+/);
    const out = [];
    const pending = [];
    const flush = () => {
        for (let index = 0; index + 1 < pending.length; index += 2) {
            const point = refToCanvas(pending[index], pending[index + 1]);
            out.push(`${round(point.x)} ${round(point.y)}`);
        }
        pending.length = 0;
    };
    for (const token of tokens) {
        if (/^[A-Za-z]$/.test(token)) {
            flush();
            out.push(token);
        }
        else if (token.length > 0) {
            pending.push(Number(token));
        }
    }
    flush();
    return out.join(' ');
}
