/**
 * THE INTERPRETATION MODEL.
 *
 * A fixed editorial vocabulary keyed to the cycle number. Nothing here is
 * generated, personalised or randomised: number in, text out. Two people in the
 * same Personal Day read the same sentences, which is the honest position for a
 * symbolic system - see docs/numerology/FORECAST_METHODOLOGY.md section 4.
 *
 * One core semantic per number; the three scales differ in HORIZON, not meaning.
 * A 4 year speaks about foundations and a 4 day speaks about finishing practical
 * tasks because that is one semantic read at two distances.
 *
 * Writing rules, enforced in review and by tests/forecastNumerologyCopy.test.mjs:
 *  - the summary names the number and the scale, so every claim is traceable
 *  - concrete verbs and nameable actions, offered rather than prescribed
 *  - cautions describe what tends to go WRONG under the theme, not warnings of harm
 *  - a symbolic emphasis, never an event: nothing "will" happen, nothing is to be
 *    "expected", no relationship ends and no money arrives because of a number
 *  - no assumed life: the reader may have no job, no application in flight, no
 *    partner, no family or household duties - a domain is written as "where work
 *    is concerned", never as a job the reader is assumed to hold
 *  - no superlatives about the cycle ("the strongest year", "the best day") and
 *    no countdowns ("four months away")
 *  - nothing medical, financial-advisory, or predictive of events
 */
